export function getDepartmentThaiName(name) {
  if (!name) return name;
  // names stored as "Hebrew / Russian" — extract the Hebrew part
  const hebrewPart = name.split('/')[0].trim();
  return thaiDepartments[hebrewPart] || name;
}
